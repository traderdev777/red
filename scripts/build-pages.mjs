#!/usr/bin/env node
/**
 * Builds the static part of apps/web for GitHub Pages into ./pages-out.
 *
 * Pages serves files only, so routes that need a server are left out:
 * /app, /login, /auth, /scan, /system, middleware, and server actions.
 * The waitlist form posts to Supabase from the browser instead (anon key, insert-only RLS).
 * The hero scan form hands off to NEXT_PUBLIC_APP_URL when set, or says the scanner isn't live.
 *
 * Env: PAGES_BASE_PATH (e.g. /red), NEXT_PUBLIC_SITE_URL, NEXT_PUBLIC_SUPABASE_URL,
 *      NEXT_PUBLIC_SUPABASE_ANON_KEY, NEXT_PUBLIC_APP_URL (optional).
 */
import { execSync } from "node:child_process";
import {
  cpSync,
  rmSync,
  existsSync,
  readFileSync,
  writeFileSync,
  writeFileSync as w,
} from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const src = join(root, "apps/web");
const tmp = join(root, "apps/.web-pages");
const out = join(root, "pages-out");
const base = (process.env.PAGES_BASE_PATH ?? "").replace(/\/$/, "");

rmSync(tmp, { recursive: true, force: true });
rmSync(out, { recursive: true, force: true });
cpSync(src, tmp, {
  recursive: true,
  verbatimSymlinks: true,
  filter: (p) => !/[\\/](\.next|\.env\.local)$/.test(p),
});

for (const p of [
  "src/app/app",
  "src/app/login",
  "src/app/auth",
  "src/app/actions",
  "src/app/scan",
  "src/app/system",
  "src/middleware.ts",
  "src/components/app",
  "src/components/auth",
  "src/components/system",
])
  rmSync(join(tmp, p), { recursive: true, force: true });

const form = join(tmp, "src/components/landing/WaitlistForm.tsx");
writeFileSync(
  form,
  readFileSync(form, "utf8").replace('"@/app/actions/waitlist"', '"@/lib/static/waitlistClient"'),
);

w(
  join(tmp, "next.config.mjs"),
  `/** Static export for GitHub Pages. Generated by scripts/build-pages.mjs. */
export default {
  output: "export",
  basePath: ${JSON.stringify(base)},
  trailingSlash: true,
  images: { unoptimized: true },
  transpilePackages: ["@red/shared"],
  poweredByHeader: false,
  reactStrictMode: true,
};
`,
);
for (const f of ["next.config.ts", "next.config.js"]) rmSync(join(tmp, f), { force: true });

try {
  execSync("npx next build", {
    cwd: tmp,
    stdio: "inherit",
    env: { ...process.env, NEXT_PUBLIC_RED_STATIC: "1", NEXT_TELEMETRY_DISABLED: "1" },
  });
  cpSync(join(tmp, "out"), out, { recursive: true });
  writeFileSync(join(out, ".nojekyll"), "");
  console.log(`\nStatic site written to ${out}${base ? ` (base path ${base})` : ""}`);
} finally {
  if (!existsSync(join(out, "index.html"))) process.exitCode = 1;
  rmSync(tmp, { recursive: true, force: true });
}
